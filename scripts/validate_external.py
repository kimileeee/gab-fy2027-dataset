def reg(s):
    s = s or ''
    m = re.match(r'(Region [IVX]+(?:-[AB])?)', s)
    if m: return m.group(1)
    t = norm(s)
    return {'cordilleraadministrativeregion': 'CAR', 'car': 'CAR', 'nationalcapitalregion': 'NCR', 'ncr': 'NCR',
            'negrosislandregion': 'NIR', 'nir': 'NIR', 'mimaropaoregion': 'MIMAROPA', 'mimaroparegion': 'MIMAROPA',
            'mimaropa': 'MIMAROPA', 'centraloffice': 'Nationwide', 'nationwide': 'Nationwide'}.get(t, s)
def prog(s):
    k = norm(s).replace('program', '')
    return 'local/national building' if k in ('', 'local', 'nationalbuilding') else k
def toks(s): return set(re.findall(r'[a-z]+|\d+', (s or '').lower())) - {'of', 'and', 'the', 'to', 'in', 'at', 'with', 'for'}
def jac(a, b):
    return len(a & b) / len(a | b) if a and b else 0.0

def match(ours, theirs, label):
    """one-to-one: bucket (region, amount) then (amount); title token-Jaccard."""
    for r in ours: r['_t'] = toks(r['item'])
    for r in theirs: r['_t'] = toks(r.get('title') or r.get('project'))
    used_o, used_t = set(), set()
    pairs = []
    def run(keyf, thr, tag):
        bo, bt = collections.defaultdict(list), collections.defaultdict(list)
        for i, r in enumerate(ours):
            if i not in used_o: bo[keyf(r, 'o')].append(i)
        for j, r in enumerate(theirs):
            if j not in used_t: bt[keyf(r, 't')].append(j)
        for k, ii in bo.items():
            jj = bt.get(k)
            if not jj: continue
            sc = sorted(((jac(ours[i]['_t'], theirs[j]['_t']), i, j) for i in ii for j in jj), reverse=True)
            for s, i, j in sc:
                if s < thr: break
                if i in used_o or j in used_t: continue
                used_o.add(i); used_t.add(j); pairs.append((i, j, s, tag))
    ka = lambda r, w: (reg(r['region_printed'] if w == 'o' else r['region']), int(r['amount'] if w == 'o' else r['amount_php']))
    kb = lambda r, w: int(r['amount'] if w == 'o' else r['amount_php'])
    run(ka, 0.5, 'same region+amount'); run(kb, 0.7, 'amount only (region differs)')
    mo = len(used_o); mt = len(used_t)
    return pairs, used_o, used_t

