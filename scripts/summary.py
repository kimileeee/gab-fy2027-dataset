"""Filed -> 2nd reading -> 3rd reading summary: whole bill, per department, per agency, with notes on what each step changed.
Writes docs/BUDGET_CHANGES.md. Stdlib only."""
import csv, collections, os
from pathlib import Path
PORK = Path(os.environ.get('PORK', 'D:/GitHub/ph-pork-graph'))
R = Path(__file__).resolve().parent.parent
S = ('GAB_FILED', 'GAB_2R', 'GAB_3R')
def rd(n):
    with open(R / 'release' / n, encoding='utf-8-sig', newline='') as f: return list(csv.DictReader(f))
def ext(p):
    with open(PORK / p, encoding='utf-8-sig', newline='') as f: return list(csv.DictReader(f))
app = rd('appropriations.csv'); ag = {a['agency_id']: a for a in rd('agencies.csv')}
dp = {d['dept_id']: d for d in rd('departments.csv')}
D = collections.defaultdict(lambda: collections.defaultdict(float)); A = collections.defaultdict(lambda: collections.defaultdict(float))
agdept = {}
FUND_CODES = {'XXXVIII', 'XXXIX', 'XL', 'XLI', 'XLII', 'XLIII'}   # special-purpose funds parsed into the release (back matter, not departments)
RF = collections.defaultdict(lambda: collections.defaultdict(float))
line = {}                                                           # (stage, appropriation_id) -> row, for the notes
for r in app:
    v = float(r['amount'] or 0); line[(r['stage'], r['appropriation_id'])] = r
    if ag[r['agency_id']]['gab_dept_code'] in FUND_CODES: RF[ag[r['agency_id']]['name_printed'].upper()][r['stage']] += v; continue
    D[r['dept_id']][r['stage']] += v; A[r['agency_id']][r['stage']] += v; agdept[(r['agency_id'], r['stage'])] = r['dept_id']
def bn(x): return f'{x/1e9:,.3f}'

# ---- notes: what the 3rd reading changed against the 2nd, line by line (the filed -> 2nd reading step is the numbers themselves)
def name_of(r):
    n = r['pap'] or r['program'] or r['label']
    return n + (f" ({r['operating_unit']})" if r['operating_unit'] and r['operating_unit'] != n else '')
CLS = (('ps', 'PS'), ('mooe', 'MOOE'), ('finex', 'FinEx'), ('co', 'CO'))
NOTE = collections.defaultdict(list)                                # ('d', dept_id) / ('a', agency_id) -> notes
def note(r, txt): NOTE[('d', r['dept_id'])].append(txt); NOTE[('a', r['agency_id'])].append(txt)
ids2 = {i for s, i in line if s == 'GAB_2R'}; ids3 = {i for s, i in line if s == 'GAB_3R'}
added = [line[('GAB_3R', i)] for i in ids3 - ids2]; removed = [line[('GAB_2R', i)] for i in ids2 - ids3]
for r in sorted(removed, key=lambda r: r['appropriation_id']):      # a same-amount, same-place removed + added pair is a rename
    twin = next((x for x in added if x['agency_id'] == r['agency_id'] and x['amount'] == r['amount'] and x['operating_unit'] == r['operating_unit']), None)
    if twin: added.remove(twin); note(r, f"3R renames “{name_of(r)}” → “{name_of(twin)}”"); continue
    note(r, f"3R drops {name_of(r)} ({-float(r['amount'])/1e9:+,.3f})")
for r in added: note(r, f"3R adds {name_of(r)} ({float(r['amount'])/1e9:+,.3f})")
for i in sorted(ids2 & ids3):
    a, b = line[('GAB_2R', i)], line[('GAB_3R', i)]
    if a['amount'] != b['amount']: note(b, f"3R: {name_of(b)} {(float(b['amount']) - float(a['amount']))/1e9:+,.3f}")
    else:
        mv = [(lbl, float(b[k] or 0) - float(a[k] or 0)) for k, lbl in CLS if (a[k] or '0') != (b[k] or '0')]
        if mv: note(b, f"3R: {name_of(b)} moves ₱{max(d for _, d in mv)/1e9:,.3f} bn {' → '.join(l for l, d in sorted(mv, key=lambda x: x[1]))}")
def notes(key, extra=()):
    n = list(extra) + NOTE.get(key, [])
    return '; '.join(n[:4]) + (f'; … {len(n) - 4} more' if len(n) > 4 else '')

def row(name, d, nt=''):
    f, t = d['GAB_FILED'], d['GAB_3R']; dl = t - f
    return f"| {name} | {bn(f)} | {bn(d['GAB_2R'])} | {bn(t)} | {dl/1e9:+,.3f} | {(dl/f*100 if f else 0):+.1f}% | {nt} |"
H = '| | As filed, ₱ bn | 2nd reading, ₱ bn | 3rd reading, ₱ bn | Change filed → 3rd, ₱ bn | % | Notes |\n|---|--:|--:|--:|--:|--:|---|'
F, T = (sum(v[s] for v in D.values()) for s in ('GAB_FILED', 'GAB_3R'))
o = ['# FY2027 GAB — what changed from filing to 2nd and 3rd reading', '',
     '> **All amounts are in billions of pesos (₱ bn).** Example: 3,858.184 = ₱3.858 trillion = ₱3,858,184,000,000. The "%" column is the change from the filed amount to the 3rd-reading amount.', '',
     'Generated by `scripts/summary.py` from `release/appropriations.csv`. **As filed** = GAB_FILED (CR 638 copy A, = NEP); **2nd reading** = GAB_2R (CR 638 copy B); '
     '**3rd reading** = GAB_3R (the four HB 10858 "FOR 3RD READING" volumes, 8 Oct 2026). **Notes** list what the 3rd reading changed against the 2nd, line by line '
     '(changed amounts, money moved between expense classes at the same total, renames, added or dropped lines); the filing → 2nd reading step is in the numbers. '
     f'Department and agency rows cover what is parsed so far ({len(D)} departments / {len(A)} agencies); the back matter is in "Full budget" below.', '',
     '## Whole bill (parsed departments and agencies)', '', H,
     row('**All parsed departments**', {s: sum(v[s] for v in D.values()) for s in S}, f'{len(NOTE) and sum(1 for k in NOTE if k[0] == "a")} agencies changed between 2nd and 3rd reading'), '']
up = sum(max(0, v['GAB_3R'] - v['GAB_FILED']) for v in D.values()); dn = sum(min(0, v['GAB_3R'] - v['GAB_FILED']) for v in D.values())

# ---- full budget: parsed departments + special purpose funds (this release where parsed, else AJ) + unprogrammed (parsed tables)
SPF = ['Budgetary Support to Government Corporations', 'Pension and Gratuity Fund', 'Allocations to Local Government Units', 'Miscellaneous Personnel Benefits Fund',
       'Revised AFP Modernization Program', 'National Disaster Risk Reduction', 'Contingent Fund']
aj = ext('data/external/ajamontesa_hgab_dept.csv'); spf = []
SAME = 'no amount on these pages changes between 2nd and 3rd reading (page-by-page comparison of the two PDFs), so 3rd = 2nd'
for n in SPF:
    rel = next((v for k, v in RF.items() if k.startswith(n.upper())), None)
    if rel: spf.append((n, {s: rel[s] for s in S}, 'this release (parsed)')); continue
    r = next(x for x in aj if x['Department'].startswith(n))
    h = float(r['House bill 2027']) * 1e9
    spf.append((r['Department'], {'GAB_FILED': float(r['NEP 2027']) * 1e9, 'GAB_2R': h, 'GAB_3R': h}, f'AJ table (not parsed here yet); {SAME}'))
U = {s: RF['UNPROGRAMMED APPROPRIATIONS'][s] for s in S}
SF = {s: sum(x[1][s] for x in spf) for s in S}
DT = {s: sum(v[s] for v in D.values()) for s in S}
def r2(name, d, nt): return f"| {name} | {bn(d['GAB_FILED'])} | {bn(d['GAB_2R'])} | {bn(d['GAB_3R'])} | {(d['GAB_3R'] - d['GAB_FILED'])/1e9:+,.3f} | {nt} |"
TOT = {s: DT[s] + SF[s] + U[s] for s in S}
full = ['## Full budget (new general appropriations) — parsed scope plus the rest', '',
 'The bill prints the whole budget in its narrative: **Total New General Appropriations ₱4,606.07 bn** = ₱3.86 trillion for departments and agencies + ₱635.90 bn Special Purpose Funds + ₱111.98 bn unprogrammed (BESF narrative, CR 638 pp. 25–26, as filed), '
 'and its Summary of New Appropriations prints ₱4,606,066,495 thousand in both CR 638 copies. The table rebuilds that total from its parts.', '',
 '| Component | As filed, ₱ bn | 2nd reading, ₱ bn | 3rd reading, ₱ bn | Change filed → 3rd, ₱ bn | Notes |', '|---|--:|--:|--:|--:|---|',
 r2(f'Departments and agencies ({len(D)}, parsed)', DT, 'this release')]
full += [r2('SPF: ' + n, d, nt) for n, d, nt in spf]
full += [r2('Special purpose funds subtotal', SF, 'sum'), r2('Unprogrammed appropriations', U, 'this release (appropriations.csv, unprogrammed = 1); standby authority, not in the NEP'),
         r2('**Total new general appropriations (rebuilt)**', TOT, 'sum'), '',
 f'Check against the printed figure: filed rebuilt {bn(TOT["GAB_FILED"])} and 2nd reading rebuilt {bn(TOT["GAB_2R"])} vs printed 4,606.066; '
 f'3rd reading rebuilt {bn(TOT["GAB_3R"])}. Filing → 2nd reading moved money between lines without changing the total (departments {(DT["GAB_2R"]-DT["GAB_FILED"])/1e9:+.3f} bn, '
 f'special purpose funds {(SF["GAB_2R"]-SF["GAB_FILED"])/1e9:+.3f} bn); 2nd → 3rd reading changes {(TOT["GAB_3R"]-TOT["GAB_2R"])/1e9:+.3f} bn in total.', '',
 'Also printed (as filed): Total Expenditure Program ₱7,200.19 bn, which adds ₱2.71 trillion of automatic appropriations (National Tax Allotment ₱1.32 trillion, interest ₱1.11 trillion, BARMM block grant ₱104.19 bn, retirement premiums ₱89.03 bn). '
 'Those are outside the GAB and not compared here.', '']
o += full
o += [f'Departments gaining (filed → 3rd): +{up/1e9:,.3f}; departments losing: {dn/1e9:,.3f}.', '', '## Per department (largest absolute change first)', '', H]
for k in sorted(D, key=lambda k: -abs(D[k]['GAB_3R'] - D[k]['GAB_FILED'])): o.append(row(f"{dp[k]['name_official']} ({dp[k]['acronym']})", D[k], notes(('d', k))))
o += ['', '## Per agency, grouped by department', '', 'Agency identity is the UACS agency code; an agency that moved department between stages is listed under its filed department and noted.', '']
by = collections.defaultdict(list)
for k in A: by[next(agdept[(k, s)] for s in S if (k, s) in agdept)].append(k)
for d in sorted(by, key=lambda d: -abs(D[d]['GAB_3R'] - D[d]['GAB_FILED'])):
    o += [f"### {dp[d]['name_official']} ({dp[d]['acronym']})", '', H]
    for k in sorted(by[d], key=lambda k: -abs(A[k]['GAB_3R'] - A[k]['GAB_FILED'])):
        ex = [f"moved to {dp[agdept[(k, s)]]['acronym']} in {s}" for s in S[1:] if (k, s) in agdept and agdept[(k, s)] != d][:1]
        ex += [f'not in {s}' for s in S if (k, s) not in agdept]
        o.append(row(ag[k]['name_official'] or ag[k]['name_printed'], A[k], notes(('a', k), ex)))
    o.append('')
(R / 'docs' / 'BUDGET_CHANGES.md').write_text('\n'.join(o) + '\n', encoding='utf-8')
