"""Filed -> 3rd reading summary: whole bill, per department, per agency. Writes docs/BUDGET_CHANGES.md. Stdlib only."""
import csv, collections, os
from pathlib import Path
PORK = Path(os.environ.get('PORK', 'D:/GitHub/ph-pork-graph'))
R = Path(__file__).resolve().parent.parent
def rd(n):
    with open(R / 'release' / n, encoding='utf-8-sig', newline='') as f: return list(csv.DictReader(f))
app = rd('appropriations.csv'); ag = {a['agency_id']: a for a in rd('agencies.csv')}
dp = {d['dept_id']: d for d in rd('departments.csv')}
D = collections.defaultdict(lambda: collections.defaultdict(float)); A = collections.defaultdict(lambda: collections.defaultdict(float))
agdept = {}
for r in app:
    v = float(r['amount'] or 0); D[r['dept_id']][r['stage']] += v; A[r['agency_id']][r['stage']] += v; agdept[(r['agency_id'], r['stage'])] = r['dept_id']
def bn(x): return f'{x/1e9:,.3f}'
def row(name, d):
    f, t = d['GAB_FILED'], d['GAB_3R']; dl = t - f
    return f'| {name} | {bn(f)} | {bn(t)} | {dl/1e9:+,.3f} | {(dl/f*100 if f else 0):+.1f}% |'
H = '| | Filed (before), ₱ bn | 3rd reading (after), ₱ bn | Change, ₱ bn | % |\n|---|--:|--:|--:|--:|'
F = sum(v['GAB_FILED'] for v in D.values()); T = sum(v['GAB_3R'] for v in D.values())
o = ['# FY2027 GAB — what changed from filed to 3rd reading', '', '> **All amounts are in billions of pesos (₱ bn).** Example: 3,858.184 = ₱3.858 trillion = ₱3,858,184,000,000. The "%" column is the change relative to the filed amount.', '',
 'Generated by `scripts/summary.py` from `release/appropriations.csv`. **Before** = GAB_FILED (CR 638 copy A, bill as filed); **after** = GAB_3R (copy B, `[3RD READING]`). ₱ billion. '
 'Covers the new appropriations parsed so far (36 departments / 318 agencies); the back matter (BSGC, pension, ALGU, calamity and contingent funds, XXXVI–XLIII) is not included, so these totals are below the bill\'s grand total.', '',
 '## Whole bill (parsed scope)', '', H, row('**All parsed departments**', {'GAB_FILED': F, 'GAB_3R': T}), '']
up = sum(max(0, v['GAB_3R'] - v['GAB_FILED']) for v in D.values()); dn = sum(min(0, v['GAB_3R'] - v['GAB_FILED']) for v in D.values())
# ---- full budget: parsed departments + back matter (AJ tables) + unprogrammed (peer page sums)
def ext(p):
    with open(PORK / p, encoding='utf-8-sig', newline='') as f: return list(csv.DictReader(f))
SPF = ['Budgetary Support to Government Corporations', 'Pension and Gratuity Fund', 'Allocations to Local Government Units', 'Miscellaneous Personnel Benefits Fund',
       'Revised AFP Modernization Program', 'National Disaster Risk Reduction', 'Contingent Fund']
aj = ext('data/external/ajamontesa_hgab_dept.csv'); spf = []
for n in SPF:
    r = next(x for x in aj if x['Department'].startswith(n)); spf.append((r['Department'].replace(' ( Calamity Fund )', ' (Calamity Fund)'), float(r['NEP 2027']) * 1e9, float(r['House bill 2027']) * 1e9))
unp = next(x for x in ext('data/gab_dept_diff.csv') if x['department'].startswith('UNPROGRAMMED'))
UF, UT = float(unp['total_A']), float(unp['total_B'])
SF, ST = sum(x[1] for x in spf), sum(x[2] for x in spf)
def r2(name, f, t, src): return f'| {name} | {bn(f)} | {bn(t)} | {(t-f)/1e9:+,.3f} | {src} |'
full = ['## Full budget (new general appropriations) — parsed scope plus the rest', '',
 'The bill prints the whole budget only in its narrative: **Total New General Appropriations ₱4,606.07 bn** = ₱3.86 trillion for departments and agencies + ₱635.90 bn Special Purpose Funds + ₱111.98 bn unprogrammed (BESF narrative, CR 638 pp. 25–26, as filed). '
 'The table rebuilds that total from its parts. The special purpose funds are the back matter we have not parsed yet; their amounts come from the AJ tables, not from this release.', '',
 '| Component | Filed (before), ₱ bn | 3rd reading (after), ₱ bn | Change, ₱ bn | Source |', '|---|--:|--:|--:|---|',
 r2('Departments and agencies (36, parsed)', F, T, 'this release')]
full += [r2('SPF: ' + n, f, t, 'AJ table') for n, f, t in spf]
full += [r2('Special purpose funds subtotal', SF, ST, 'AJ table'), r2('Unprogrammed appropriations', UF, UT, 'page sums of the bill (data/gab_dept_diff.csv)'),
         r2('**Total new general appropriations (rebuilt)**', F + SF + UF, T + ST + UT, 'sum'), '',
 f'Check against the printed figure: filed rebuilt {bn(F+SF+UF)} vs printed 4,606.07 (difference {(F+SF+UF)/1e9-4606.07:+.3f} bn, rounding). The 3rd-reading total is not printed anywhere; rebuilt it is {bn(T+ST+UT)}, '
 f'a net change of {(T+ST+UT-F-SF-UF)/1e9:+.3f} bn, i.e. the House moved money between lines rather than raising the total (departments {(T-F)/1e9:+.3f} bn, special purpose funds {(ST-SF)/1e9:+.3f} bn).', '',
 'Also printed (as filed): Total Expenditure Program ₱7,200.19 bn, which adds ₱2.71 trillion of automatic appropriations (National Tax Allotment ₱1.32 trillion, interest ₱1.11 trillion, BARMM block grant ₱104.19 bn, retirement premiums ₱89.03 bn). '
 'Those are outside the GAB and not compared here.', '']
o += full
o += [f'Departments gaining: +{up/1e9:,.3f}; departments losing: {dn/1e9:,.3f}.', '', '## Per department (largest absolute change first)', '', H]
for k in sorted(D, key=lambda k: -abs(D[k]['GAB_3R'] - D[k]['GAB_FILED'])): o.append(row(f"{dp[k]['name_official']} ({dp[k]['acronym']})", D[k]))
o += ['', '## Per agency, grouped by department', '', 'Agency identity is the UACS agency code; an agency that moved department between stages is listed under its filed department and marked.', '']
by = collections.defaultdict(list)
for k, v in A.items():
    d0 = agdept.get((k, 'GAB_FILED')) or agdept[(k, 'GAB_3R')]; by[d0].append(k)
for d in sorted(by, key=lambda d: -abs(D[d]['GAB_3R'] - D[d]['GAB_FILED'])):
    o += [f"### {dp[d]['name_official']} ({dp[d]['acronym']})", '', H]
    for k in sorted(by[d], key=lambda k: -abs(A[k]['GAB_3R'] - A[k]['GAB_FILED'])):
        nm = ag[k]['name_official'] or ag[k]['name_printed']
        if agdept.get((k, 'GAB_3R'), d) != d and (k, 'GAB_3R') in agdept: nm += f" (moved to {dp[agdept[(k,'GAB_3R')]]['acronym']})"
        if (k, 'GAB_FILED') not in agdept: nm += ' (new in 3R)'
        if (k, 'GAB_3R') not in agdept: nm += ' (absent in 3R)'
        o.append(row(nm, A[k]))
    o.append('')
(R / 'docs' / 'BUDGET_CHANGES.md').write_text('\n'.join(o) + '\n', encoding='utf-8')
